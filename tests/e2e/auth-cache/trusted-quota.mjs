// Native Redis enforcement through the managed session ingress. Mock inference
// only; provider credentials, session tokens and request bodies are never logged.
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import path from 'node:path';
import {rm} from 'node:fs/promises';

export async function trustedQuotaAcceptance(ctx) {
  const {command, kubectl, apply, forward, until, admin, gateway, alice, bob, model, record, report, cluster, work} = ctx;
  const archive = path.join(work, 'access-redis.tar');
  await command('docker', ['image', 'save', '--platform=linux/amd64', '-o', archive, 'redis:7-alpine']);
  await command(process.env.KIND ?? 'kind', ['load', 'image-archive', '--name', cluster, archive]);
  await rm(archive);
  const metadata = name => ({name, namespace: 'aep-system'});
  await apply([
    {apiVersion: 'apps/v1', kind: 'Deployment', metadata: metadata('access-redis'), spec: {replicas: 1,
      selector: {matchLabels: {app: 'access-redis'}}, template: {metadata: {labels: {app: 'access-redis'}}, spec: {
        automountServiceAccountToken: false,
        securityContext: {runAsNonRoot: true, runAsUser: 1000, runAsGroup: 1000, fsGroup: 1000, seccompProfile: {type: 'RuntimeDefault'}},
        containers: [{name: 'redis', image: 'redis:7-alpine',
          securityContext: {allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: {drop: ['ALL']}},
          resources: {requests: {cpu: '20m', memory: '32Mi'}, limits: {memory: '128Mi'}},
          command: ['redis-server', '--save', '', '--appendonly', 'no'], readinessProbe: {tcpSocket: {port: 6379}},
          volumeMounts: [{name: 'data', mountPath: '/data'}]}], volumes: [{name: 'data', emptyDir: {}}]}}}},
    {apiVersion: 'v1', kind: 'Service', metadata: metadata('access-redis'), spec: {selector: {app: 'access-redis'}, ports: [{port: 6379}]}},
    // Higress consumes the namespace's singleton default McpBridge.
    {apiVersion: 'networking.higress.io/v1', kind: 'McpBridge', metadata: {name: 'default', namespace: 'higress-system'},
      spec: {registries: [{name: 'access-redis', type: 'dns', domain: 'access-redis.aep-system.svc.cluster.local', port: 6379, protocol: 'http'}]}},
    {apiVersion: 'networking.k8s.io/v1', kind: 'Ingress', metadata: {name: 'access-redis-discovery', namespace: 'higress-system',
      annotations: {'higress.io/destination': 'access-redis.dns'}}, spec: {ingressClassName: 'higress', rules: [{http: {paths: [{
        path: '/access-redis-unused', pathType: 'Prefix', backend: {service: {name: 'access-redis', port: {number: 6379}}}}]}}]}},
  ]);
  await kubectl(['-n', 'aep-system', 'rollout', 'status', 'deployment/access-redis', '--timeout=120s']);
  const redis = (...args) => kubectl(['-n', 'aep-system', 'exec', 'deployment/access-redis', '--', 'redis-cli', ...args]);
  await kubectl(['-n', 'aep-system', 'patch', 'deploymentconfig', 'deployment', '--type=merge', '-p', JSON.stringify({
    spec: {nativeGateway: {enabled: true, redisService: 'access-redis.dns', redisPort: 6379, redisDatabase: 0}},
  })]);
  const adminPort = await forward('deployment/higress-gateway', 15000, 'higress-system');
  // A later Control restart replaces the local port-forward. Callers that run
  // after that fault scenario supply their reconnected client/token store.
  const publication = (client = admin) => client.createDataPlanePublication(randomBytes(12).toString('hex'), {includeGatewayLimits: true});
  async function loaded(id, modelId = model.id) {
    const plugins = JSON.parse(await kubectl(['-n', 'higress-system', 'get', 'wasmplugins', '-o', 'json'])).items;
    // Names are generated by the production renderer, not reimplemented here.
    const plugin = plugins.find(p => p.spec.matchRules?.some(r => r.config?.rule_name === p.metadata.name) && p.metadata.name === id);
    assert(plugin, 'Operator has not rendered the current native rule');
    const dump = await (await fetch('http://127.0.0.1:' + adminPort + '/config_dump', {signal: AbortSignal.timeout(5000)})).json();
    const active = dump.configs.flatMap(c => c.dynamic_listeners ?? []).map(l => l.active_state).filter(Boolean);
    assert(JSON.stringify(active).includes(id), 'Native rule is not loaded in an active Higress listener');
    const stats = await (await fetch('http://127.0.0.1:' + adminPort + '/stats?filter=' + id + '.*update_success', {signal: AbortSignal.timeout(5000)})).text();
    assert(/\.update_success: [1-9][0-9]*/.test(stats), 'Native WASM extension is not ready');
    const extensions = dump.configs.flatMap(c => c.ecds_filters ?? []).map(e => e.ecds_filter).filter(e => e.name?.includes(id));
    const rules = extensions.flatMap(e => JSON.parse(e.typed_config.config.configuration.value)._rules_ ?? []);
    assert(rules.some(r => r.rule_name === id && r._match_route_?.length), 'Native matching configuration is not loaded');
    const clusters = dump.configs.flatMap(c => c.dynamic_active_clusters ?? []).map(c => c.cluster?.name);
    assert(clusters.some(name => name?.includes('access-redis')), 'Native Redis discovery cluster is not loaded');
    // A publication replaces multiple independently delivered xDS resources.
    // Loading the new limit alone does not prove the provider route survived
    // the fail-closed transition to that snapshot. Do not probe inference until
    // actual RDS, CDS and the matching ai-proxy rule have converged together.
    const providerRules = dump.configs.flatMap(c => c.ecds_filters ?? []).map(e => e.ecds_filter)
      .filter(e => e.name?.includes('.aep-ai-proxy-'))
      .flatMap(e => JSON.parse(e.typed_config.config.configuration.value)._rules_ ?? []);
    const provider = providerRules.find(r => r.provider?.modelMapping?.[modelId]);
    assert(provider, 'Current model mapping is not loaded in native ai-proxy');
    const routes = dump.configs.flatMap(c => c.dynamic_route_configs ?? []).flatMap(c => c.route_config?.virtual_hosts ?? [])
      .flatMap(v => v.routes ?? []);
    assert(provider._match_route_?.some(name => clusters.includes(name) && routes.some(r => r.name === name && r.route?.cluster === name)),
      'Current model provider route/cluster has not converged');
  }
  async function rulePlugin(expected) {
    const policies = JSON.parse(await kubectl(['-n', 'aep-system', 'get', 'modelpolicies', '-o', 'json'])).items;
    const policy = policies.find(p => !p.spec.disabled && p.spec.nativeRule?.id === expected.id && p.spec.nativeRule.version === expected.version);
    assert(policy, 'Current business rule/version has not reached ModelPolicy');
    const deployment = JSON.parse(await kubectl(['-n', 'aep-system', 'get', 'deploymentconfig', 'deployment', '-o', 'json']));
    const sequence = 'gateway.aep.zhiyuan.io/publication-sequence';
    assert.equal(policy.metadata.annotations[sequence], deployment.metadata.annotations[sequence], 'Current publication is still being delivered');
    for (const object of [deployment, policy]) {
      assert.equal(object.status?.observedGeneration, object.metadata.generation, 'Operator has not observed the current generation');
      assert.equal(object.status?.observedPublication?.sequence, Number(object.metadata.annotations[sequence]));
      assert.equal(object.status?.conditions?.find(c => c.type === 'Applied')?.status, 'True');
      assert(object.status.appliedSnapshot);
      assert.equal(object.status.appliedSnapshot, deployment.status.appliedSnapshot);
    }
    const list = JSON.parse(await kubectl(['-n', 'higress-system', 'get', 'wasmplugins', '-o', 'json'])).items;
    const limits = list.filter(p => p.metadata.name.startsWith('aep-limit-') && p.spec.matchRules?.length &&
      p.metadata.annotations?.['gateway.aep.zhiyuan.io/snapshot'] === deployment.status.appliedSnapshot);
    assert.equal(limits.length, 1);
    return limits[0].metadata.name;
  }
  const grant = async person => JSON.parse(await kubectl(['-n', 'aep-system', 'get', 'modelaccessgrant', 'access-' + person.binding, '-o', 'json'])).spec;
  const aliceGrant = await grant(alice), bobGrant = await grant(bob);
  const sharedTeam = aliceGrant.teamIds.find(id => !bobGrant.teamIds.includes(id));
  await admin.replaceUserRBAC(bob.user.id, {roleIds: bobGrant.roleIds, teamIds: [...bobGrant.teamIds, sharedTeam]});
  await until(async () => assert((await grant(bob)).teamIds.includes(sharedTeam)));
  await until(async () => assert.equal((await gateway.call(bob)).status, 200));
  const effectiveBob = await grant(bob);
  const sharedEffectiveRole = aliceGrant.roleIds.find(id => effectiveBob.roleIds.includes(id));
  assert(sharedEffectiveRole, 'No shared effective role from the team default');
  let previous;
  for (const [kind, scopeType, scopeId, modelId, shared] of [
    ['requests', 'user', alice.user.id, null, false], ['requests', 'user', alice.user.id, model.id, false],
    ['requests', 'team', sharedTeam, model.id, true],
    ['requests', 'role', sharedEffectiveRole, model.id, true],
    ['requests', 'model', model.id, null, true], ['requests', 'global', null, null, true],
    ['tokens', 'user', alice.user.id, model.id, false], ['tokens', 'team', sharedTeam, model.id, true],
  ]) {
    if (previous) await admin.deleteGatewayLimit(previous.id, previous.version);
    const id = 'managed-' + randomBytes(5).toString('hex');
    previous = await admin.putGatewayLimit(id, {kind, scopeType, scopeId, modelId, maximum: 1, interval: 'minute', enabled: true, expectedVersion: 0});
    await publication();
    const name = await until(() => rulePlugin(previous));
    await until(() => loaded(name));
    await redis('FLUSHDB'); // Only the isolated test-owned, emptyDir Redis.
    const first = await gateway.call(alice);
    assert.equal(first.status, 200, scopeType + ' initial request');
    const firstKeys = (await redis('--scan')).split(/\r?\n/).filter(Boolean);
    const firstCounters = await Promise.all(firstKeys.map(async key => ({key, value: await redis('GET', key)})));
    if (kind === 'tokens') await until(async () => {
      const keys = (await redis('--scan', '--pattern', 'higress-token-ratelimit*')).split(/\r?\n/).filter(Boolean);
      assert.equal(keys.length, 1);
      assert.equal(await redis('GET', keys[0]), '2', 'Native Token count must equal mock provider usage');
    });
    const before = await gateway.stats();
    const forged = {'x-mse-consumer': 'quota-admin', 'x-aep-user-id': bob.user.id, 'x-aep-limit-foreign': '1'};
    const limited = await gateway.call(alice, model.id, {headers: forged});
    if (limited.status !== 429) {
      const keys = (await redis('--scan')).split(/\r?\n/).filter(Boolean);
      const plugin = JSON.parse(await kubectl(['-n', 'higress-system', 'get', 'wasmplugin', name, '-o', 'json']));
      const config = plugin.spec.matchRules[0].config;
      const header = config.rule_items?.[0]?.limit_by_header;
      report.nativeLimitFailure = {kind, scopeType, plugin: name, header, firstPresence: first.body.identity?.[header],
        secondPresence: limited.body?.identity?.[header], rule: config.rule_items?.[0]?.limit_keys,
        firstCounters,
        redis: await Promise.all(keys.map(async key => ({key, value: await redis('GET', key), ttl: await redis('TTL', key)}))),
        connections: await (await fetch('http://127.0.0.1:' + adminPort + '/stats?filter=redis.*upstream_cx')).text()};
      const dump = await (await fetch('http://127.0.0.1:' + adminPort + '/config_dump')).json();
      const paths = [];
      function find(value, path = '') {
        if (typeof value === 'string' && value.includes(name)) paths.push(path);
        else if (value && typeof value === 'object') for (const [key, item] of Object.entries(value)) find(item, path + '/' + key);
      }
      find(dump);
      report.nativeLimitFailure.loadedPaths = paths;
      report.nativeLimitFailure.matches = dump.configs.flatMap(c => c.ecds_filters ?? []).map(e => e.ecds_filter)
        .filter(e => e.name?.includes(name)).flatMap(e => JSON.parse(e.typed_config.config.configuration.value)._rules_ ?? [])
        .map(r => ({name: r.rule_name, routes: r._match_route_}));
      report.nativeLimitFailure.routes = dump.configs.flatMap(c => c.dynamic_route_configs ?? [])
        .flatMap(c => c.route_config?.virtual_hosts ?? []).flatMap(v => v.routes ?? [])
        .map(r => ({name: r.name, metadata: r.metadata}));
      report.nativeLimitFailure.clusters = dump.configs.flatMap(c => c.dynamic_active_clusters ?? []).map(c => c.cluster?.name);
      report.nativeLimitFailure.hostHealth = (await (await fetch('http://127.0.0.1:' + adminPort + '/clusters?format=json')).json())
        .cluster_statuses.filter(c => c.name?.includes('redis')).map(c => ({name: c.name, hosts: c.host_statuses?.map(h => h.health_status)}));
      const logs = await kubectl(['-n', 'higress-system', 'logs', 'deployment/higress-gateway', '--tail=200']);
      report.nativeLimitFailure.redisErrors = [...logs.matchAll(/redis (?:call failed|response parse error):[^\r\n]*/g)].map(m => m[0]);
      report.nativeLimitFailure.followUpStatus = (await gateway.call(alice)).status;
    }
    assert.equal(limited.status, 429, scopeType + ' limit bypassed');
    assert.equal(await gateway.stats(), before, 'rejected native limit reached provider');
    assert.equal((await gateway.call(bob)).status, shared ? 429 : 200, scopeType + ' counter isolation/sharing');
    assert((await redis('--scan')).length > 0, 'No native Redis counter was created');
    record('Native Redis ' + kind + ' limit enforces ' + scopeType + (modelId ? ' x model' : '') + '; forged identity cannot bypass');
  }
  await admin.deleteGatewayLimit(previous.id, previous.version);
  await publication();
  await until(async () => assert.equal((await gateway.call(alice)).status, 200));
  await admin.replaceUserRBAC(bob.user.id, {roleIds: bobGrant.roleIds, teamIds: bobGrant.teamIds});
  await until(async () => assert.deepEqual((await grant(bob)).teamIds.sort(), bobGrant.teamIds.sort()));
  await until(async () => assert.equal((await gateway.call(bob)).status, 200));
  report.quotaIdentityVerified = true;
  report.persistentQuotaAPIIntegrated = false;
  gateway.nativeRedis = {redis, publication, loaded, rulePlugin};
  record('Deleting the native rule restores inference; membership restoration republishes the affected grant');
}
